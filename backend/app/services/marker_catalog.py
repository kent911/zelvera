_BY_KEY: dict[str, dict[str, Any]] = {e["key"]: e for e in CATALOG}

# Сопоставление нормализованных синонимов -> канонический ключ.
SYNONYMS: dict[str, str] = {}
_DUPLICATES: list[str] = []
for _e in CATALOG:
    _syns = [_e["name"], *_e.get("synonyms", [])]
    for _s in _syns:
        _k = _norm(_s)
        if not _k:
            continue
        if _k in SYNONYMS and SYNONYMS[_k] != _e["key"]:
            _DUPLICATES.append(f"{_k}: {SYNONYMS[_k]} vs {_e['key']}")
            continue
        SYNONYMS[_k] = _e["key"]
if _DUPLICATES:
    raise ValueError("Конфликт синонимов в marker_catalog: " + "; ".join(_DUPLICATES))

del _e, _s, _syns, _k, _DUPLICATES


def entry_for(name: str) -> dict[str, Any] | None:
    """Возвращает запись каталога для имени маркера (или None)."""
    key = SYNONYMS.get(_norm(name))
    return _BY_KEY.get(key) if key else None


def canonical_key(name: str) -> str | None:
    """Канонический ключ маркера (None, если в каталоге не найден)."""
    return SYNONYMS.get(_norm(name))


def canonical_name(name: str) -> str:
    """Каноническое отображаемое имя; при отсутствии в каталоге —
    очищенное исходное имя."""
    entry = entry_for(name)
    if entry:
        return entry["name"]
    return " ".join(str(name or "").split())


def list_catalog() -> list[dict[str, Any]]:
    """Полный каталог для отображения/API."""
    return [
        {"key": e["key"], "name": e["name"], "category": e["category"]}
        for e in CATALOG
    ]
