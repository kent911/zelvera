let LANG = (() => {
  try {
    const v = localStorage.getItem(LANG_KEY);
    return v === "en" ? "en" : "ru";
  } catch {
    return "ru";
  }
})();

function t(key, vars) {
  const table = I18N_STRINGS[LANG] || I18N_STRINGS.ru;
  let text =
    table[key] != null ? table[key] : I18N_STRINGS.ru[key] != null ? I18N_STRINGS.ru[key] : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}

function applyI18n() {
  document.documentElement.lang = LANG;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const title = t(el.getAttribute("data-i18n-title"));
    el.title = title;
    if (el.hasAttribute("aria-label")) el.setAttribute("aria-label", title);
  });
  const toggle = document.getElementById("lang-toggle");
  if (toggle) toggle.textContent = LANG === "ru" ? "EN" : "RU";
}

function setLang(lang) {
  LANG = lang === "en" ? "en" : "ru";
  try {
    localStorage.setItem(LANG_KEY, LANG);
  } catch {
    /* no storage available */
  }
  applyI18n();
  syncLangToBackend();
  refreshLocalizedViews();
}

async function syncLangToBackend() {
  try {
    await fetch("/api/settings", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ lang: LANG }),
    });
  } catch {
    /* non-critical */
  }
}

function refreshLocalizedViews() {
  if (typeof loadProfiles === "function") loadProfiles();
  if (typeof loadRecords === "function" && cardView && !cardView.classList.contains("hidden")) {
    loadRecords();
    const btn = document.getElementById("btn-trends");
    if (btn) btn.textContent = t("card.trends");
  }
  if (typeof loadArticles === "function" && articlesView && !articlesView.classList.contains("hidden")) {
    loadArticles();
  }
  if (typeof loadNotes === "function" && notesView && !notesView.classList.contains("hidden")) {
    loadNotes();
  }
  if (typeof loadMemory === "function" && memoryView && !memoryView.classList.contains("hidden")) {
    loadMemory();
  }
  if (typeof fillMemoryCatSelect === "function") fillMemoryCatSelect();
  const voiceBtn = document.getElementById("btn-voice");
  if (voiceBtn && recognition) {
    recognition.lang = LANG === "en" ? "en-US" : "ru-RU";
  }
}
